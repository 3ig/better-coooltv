"""
Generates the launcher artwork as vector drawables (sharp on 1080p and 4K launchers):
  drawable/banner.xml                 Android TV home-screen banner (320x180)
  drawable/ic_launcher_foreground.xml adaptive icon foreground
  mipmap-anydpi-v26/ic_launcher.xml   adaptive icon (Android 8+)
  mipmap-anydpi/ic_launcher.xml       plain vector icon (Android 7)

Text is converted to outlines from macOS's SF Compact Rounded, so the output has no font dependency.
Run with a Python that has fonttools:  python scripts/make_icons.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from fontTools.pens.svgPathPen import SVGPathPen  # noqa: E402
from fontTools.pens.transformPen import TransformPen  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402
from fontTools.varLib.instancer import instantiateVariableFont  # noqa: E402

GREEN = "#FFA8B43A"   # coool.tv lime toned down from the original #BFCD31 (matches the app default)
GREEN_DARK = "#FF5C691F"
INK = "#FF0E0E12"     # coool.tv slate-900 background
WHITE = "#FFFFFFFF"

RES = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")

font = TTFont("/System/Library/Fonts/SFCompactRounded.ttf")
if "fvar" in font:
    font = instantiateVariableFont(font, {"wght": 700}, inplace=False)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
UPM = font["head"].unitsPerEm
X_HEIGHT = font["OS/2"].sxHeight or UPM * 0.5


def text_path(text, x_height, x, baseline, tracking=0.0):
    """Outline path for `text` with the given x-height, starting at (x, baseline)."""
    s = x_height / X_HEIGHT
    pen = SVGPathPen(glyphs, lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    cx = 0.0
    for ch in text:
        g = cmap[ord(ch)]
        glyphs[g].draw(TransformPen(pen, (s, 0, 0, -s, x + cx * s, baseline)))
        cx += glyphs[g].width + tracking * UPM
    return pen.getCommands()


def play(cx, cy, size):
    """Equilateral-ish play triangle centred optically on (cx, cy)."""
    h = size
    w = size * 0.88
    x0 = cx - w * 0.42
    return f"M{x0:.2f},{cy - h / 2:.2f} L{x0 + w:.2f},{cy:.2f} L{x0:.2f},{cy + h / 2:.2f} Z"


def rounded_rect(x, y, w, h, r):
    return (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
            f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} "
            f"V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z")


def write(rel, content):
    path = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print("wrote", rel)


HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/make_icons.py — edit the script, not this file. -->\n'

# ---- TV banner 320x180: lime screen badge with a play mark, wordmark, soft lime glow ----
badge = rounded_rect(26, 46, 88, 88, 24)
banner = HEADER + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="320dp" android:height="180dp"
    android:viewportWidth="320" android:viewportHeight="180">
    <path android:fillColor="{INK}" android:pathData="M0,0h320v180h-320z" />
    <path android:pathData="M0,0h320v180h-320z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="70" android:centerY="96" android:gradientRadius="170">
                <item android:offset="0" android:color="#38A8B43A" />
                <item android:offset="1" android:color="#00A8B43A" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:fillColor="{GREEN_DARK}" android:pathData="{rounded_rect(26, 50, 88, 88, 24)}" />
    <path android:fillColor="{GREEN}" android:pathData="{badge}" />
    <path android:fillColor="{INK}" android:strokeColor="{INK}" android:strokeWidth="7"
        android:strokeLineJoin="round" android:pathData="{play(72, 90, 34)}" />
    <path android:fillColor="{WHITE}" android:pathData="{text_path('coool tv', 24, 134, 99)}" />
    <path android:fillColor="{GREEN}" android:pathData="{text_path('lite', 13, 135, 125, 0.06)}" />
</vector>
"""
write("drawable/banner.xml", banner)

# ---- Adaptive icon (108x108, keep content inside the 66dp safe zone) ----
foreground = HEADER + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{INK}" android:strokeColor="{INK}" android:strokeWidth="6"
        android:strokeLineJoin="round" android:pathData="{play(56, 54, 30)}" />
</vector>
"""
write("drawable/ic_launcher_foreground.xml", foreground)

write("values/ic_launcher_colors.xml", HEADER + f"""<resources>
    <color name="ic_launcher_background">{GREEN}</color>
</resources>
""")

write("mipmap-anydpi-v26/ic_launcher.xml", HEADER + """<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
""")

# ---- Android 7: rounded lime square with the play mark ----
write("mipmap-anydpi/ic_launcher.xml", HEADER + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp" android:height="48dp"
    android:viewportWidth="48" android:viewportHeight="48">
    <path android:fillColor="{GREEN}" android:pathData="{rounded_rect(2, 2, 44, 44, 12)}" />
    <path android:fillColor="{INK}" android:strokeColor="{INK}" android:strokeWidth="3"
        android:strokeLineJoin="round" android:pathData="{play(25, 24, 15)}" />
</vector>
""")
